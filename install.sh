#!/usr/bin/env bash
#
# Orb Hospital OS — one-command installer.
#
# Idempotent and re-runnable: it never overwrites secrets, an existing .env, or an
# existing TLS cert. It sets up a Python venv, installs backend deps, generates
# secrets + a self-signed dev TLS cert (real cert instructions printed), runs DB
# migrations via the versioned runner, optionally builds the frontend, and prints
# clear next steps.
#
# Usage:
#   ./install.sh                 # full install (backend + frontend build)
#   ./install.sh --backend-only  # skip the npm build (backend-only host)
#   ./install.sh --skip-frontend # alias for --backend-only
#   ./install.sh --help
#
set -euo pipefail

# ── Locations ────────────────────────────────────────────────────────────────
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVER_DIR="$REPO_ROOT/server"
VENV_DIR="$SERVER_DIR/.venv"
ENV_FILE="$REPO_ROOT/.env"
CERTS_DIR="$REPO_ROOT/certs"
REQUIREMENTS="$SERVER_DIR/requirements.txt"

BUILD_FRONTEND=1

# ── Pretty output helpers ────────────────────────────────────────────────────
info()  { printf '\033[0;34m[info]\033[0m  %s\n' "$*"; }
ok()    { printf '\033[0;32m[ ok ]\033[0m  %s\n' "$*"; }
warn()  { printf '\033[0;33m[warn]\033[0m  %s\n' "$*" >&2; }
err()   { printf '\033[0;31m[fail]\033[0m  %s\n' "$*" >&2; }
step()  { printf '\n\033[1m── %s ──\033[0m\n' "$*"; }

usage() {
    sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0
}

# ── Parse args ───────────────────────────────────────────────────────────────
for arg in "$@"; do
    case "$arg" in
        --backend-only|--skip-frontend) BUILD_FRONTEND=0 ;;
        -h|--help) usage ;;
        *) err "Unknown option: $arg"; echo "Try: ./install.sh --help" >&2; exit 2 ;;
    esac
done

# ── Preflight checks ─────────────────────────────────────────────────────────
step "Preflight checks"

# python3 >= 3.11
if ! command -v python3 >/dev/null 2>&1; then
    err "python3 not found. Install Python 3.11+ and re-run."
    exit 1
fi
PY_VER="$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])')"
PY_OK="$(python3 -c 'import sys; print(1 if sys.version_info[:2] >= (3, 11) else 0)')"
if [ "$PY_OK" = "1" ]; then
    ok "python3 $PY_VER"
else
    warn "python3 $PY_VER found, but 3.11+ is recommended. Continuing anyway."
fi

if command -v openssl >/dev/null 2>&1; then
    ok "openssl $(openssl version 2>/dev/null | awk '{print $2}')"
else
    err "openssl not found — required to generate secrets and TLS certs. Install it and re-run."
    exit 1
fi

if [ "$BUILD_FRONTEND" -eq 1 ]; then
    if command -v node >/dev/null 2>&1 && command -v npm >/dev/null 2>&1; then
        ok "node $(node --version 2>/dev/null)"
    else
        warn "node/npm not found — skipping frontend build. Re-run with node installed, or use --backend-only."
        BUILD_FRONTEND=0
    fi
else
    info "Frontend build disabled (--backend-only)."
fi

# ── Python venv + backend deps ───────────────────────────────────────────────
step "Python virtual environment"
if [ ! -d "$VENV_DIR" ]; then
    info "Creating venv at $VENV_DIR"
    python3 -m venv "$VENV_DIR"
    ok "venv created"
else
    ok "venv already exists — reusing"
fi

# shellcheck disable=SC1091
. "$VENV_DIR/bin/activate"

info "Upgrading pip"
python -m pip install --quiet --upgrade pip

if [ -f "$REQUIREMENTS" ]; then
    info "Installing backend dependencies from $REQUIREMENTS (this can take a while)"
    if ! python -m pip install -r "$REQUIREMENTS"; then
        warn "pip install reported errors (some pins have heavy/native builds — e.g. torch, whisper)."
        warn "The core API deps may still be usable; review the output above."
    else
        ok "backend dependencies installed"
    fi
else
    err "requirements file not found at $REQUIREMENTS"
    exit 1
fi

# ── Secret generation (never overwrite an existing .env) ─────────────────────
step "Secrets (.env)"
gen_secret() { openssl rand -hex 32; }

if [ -f "$ENV_FILE" ]; then
    ok ".env already exists — NOT overwriting (secrets preserved)."
else
    info "Generating fresh secrets into $ENV_FILE"
    umask 077
    cat > "$ENV_FILE" <<EOF
# Orb Hospital OS — environment configuration
# Generated by install.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ").
# Keep this file secret (chmod 600). Do NOT commit it.

# Deployment profile: dev | prod
ORB_DEPLOYMENT_PROFILE=prod

# ── Secrets (freshly generated) ──
ORB_JWT_SECRET=$(gen_secret)
ORB_INGESTION_API_KEY=$(gen_secret)
ORB_DB_ENCRYPTION_KEY=$(gen_secret)
ORB_UPLOAD_ENCRYPTION_KEY=$(gen_secret)
# Signs the patient discharge-portal grants. Separate from the staff JWT secret
# so a leak or rotation of one does not reach the other.
ORB_DISCHARGE_JWT_SECRET=$(gen_secret)
# Uploads refuse to save if they cannot be encrypted (the prod default, written
# out so nobody has to know that).
ORB_REQUIRE_UPLOAD_ENCRYPTION=1

# ── Server ──
ORB_HOST=127.0.0.1
ORB_PORT=8000

# ── Patient discharge link (install runbook, sections 7 and 8.4) ──
# The https address a patient's phone opens from the discharge QR code, usually
# the same address staff type. Until it is set, the prod profile prints no
# discharge link or QR code at all, and says so in the startup log.
# ORB_PUBLIC_APP_BASE_URL=https://orb.hospital.local:8000

# ── TLS (in transit). Point these at a REAL cert in production. ──
ORB_TLS_CERT=$CERTS_DIR/orb.crt
ORB_TLS_KEY=$CERTS_DIR/orb.key

# ── Optional: gate the Prometheus /metrics endpoint behind a bearer token. ──
# ORB_METRICS_TOKEN=$(gen_secret)
EOF
    chmod 600 "$ENV_FILE"
    ok "Secrets written and .env locked to 0600."
fi

# ── Self-signed TLS cert (dev only; never overwrite) ─────────────────────────
step "TLS certificate"
mkdir -p "$CERTS_DIR"
if [ -f "$CERTS_DIR/orb.crt" ] && [ -f "$CERTS_DIR/orb.key" ]; then
    ok "TLS cert already present at $CERTS_DIR — leaving it in place."
else
    info "Generating a self-signed certificate (DEV ONLY) into $CERTS_DIR"
    openssl req -x509 -newkey rsa:4096 -sha256 -days 365 -nodes \
        -keyout "$CERTS_DIR/orb.key" -out "$CERTS_DIR/orb.crt" \
        -subj "/C=US/ST=Local/L=Local/O=Orb Hospital OS/CN=localhost" \
        -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" 2>/dev/null
    chmod 600 "$CERTS_DIR/orb.key"
    ok "Self-signed cert created (valid 365 days)."
    warn "This is a DEV cert. For production, replace both files with a CA-issued cert:"
    warn "    cp /path/to/fullchain.pem $CERTS_DIR/orb.crt"
    warn "    cp /path/to/privkey.pem   $CERTS_DIR/orb.key"
    warn "  (or terminate TLS at a reverse proxy and unset ORB_TLS_CERT/ORB_TLS_KEY)."
fi

# ── Database migrations (via the versioned runner) ───────────────────────────
step "Database migrations"
# Load the generated secrets so config.py's prod fail-closed guards are satisfied
# while we run migrations.
set -a
# shellcheck disable=SC1090
. "$ENV_FILE"
set +a
info "Running migration runner (server/migrate.py)"
( cd "$REPO_ROOT" && python server/migrate.py )
ok "Migrations applied."

# ── First admin account (bootstrap login) ────────────────────────────────────
step "Admin account"
# Migrations alone leave NO account anyone can sign in with: init_db seeds only the
# 'system' row, whose placeholder hash can never verify, and the user-creation API
# requires an already-authenticated admin. This step is idempotent — it exits
# immediately when a real admin already exists, so re-running install.sh is safe.
ADMIN_RC=0
( cd "$REPO_ROOT" && python server/scripts/create_admin.py --enroll-mfa ) || ADMIN_RC=$?
# Exit 2 is create_admin.py's specific "there is NO admin and this run did not
# create one" code. It must NOT be lumped in with a generic failure and buried
# in a warn line: an appliance in that state boots, serves, and cannot be signed
# into by anybody — discovered on go-live morning, at a bedside. Fail the install.
if [ "$ADMIN_RC" -eq 2 ]; then
    printf '\n' >&2
    err "NO ADMINISTRATOR ACCOUNT EXISTS on this appliance."
    err "Orb would start, serve the API, and be impossible for anyone to sign in to."
    err "There is no network path to create one (user creation requires an admin)."
    err ""
    err "Run this at the console, then re-run ./install.sh:"
    err "    cd $REPO_ROOT && set -a && . ./.env && set +a"
    err "    server/.venv/bin/python server/scripts/create_admin.py --enroll-mfa"
    exit 1
elif [ "$ADMIN_RC" -ne 0 ]; then
    warn "Admin bootstrap did not complete cleanly (exit $ADMIN_RC) — most likely the"
    warn "password was refused by policy, or MFA enrolment was skipped."
    warn "Check the posture before go-live:"
    warn "    cd $REPO_ROOT && set -a && . ./.env && set +a"
    warn "    server/.venv/bin/python server/scripts/access_review.py --deep"
fi

# ── Frontend build (guarded) ─────────────────────────────────────────────────
if [ "$BUILD_FRONTEND" -eq 1 ]; then
    step "Frontend build"
    ( cd "$REPO_ROOT" && \
      if [ -f package-lock.json ]; then npm ci; else npm install; fi && \
      npm run build )
    ok "Frontend built into ./dist"
else
    info "Skipping frontend build."
fi

# ── Nightly encrypted backup hint ────────────────────────────────────────────
step "Backups"
info "A backup helper is provided at scripts/backup.sh (encrypted, timestamped, 14-day rotation)."
info "Schedule it nightly. Example cron entry (crontab -e):"
cat <<EOF
    # Orb encrypted DB backup, nightly at 02:30
    30 2 * * * cd $REPO_ROOT && set -a && . ./.env && set +a && ./scripts/backup.sh >> /var/log/orb-backup.log 2>&1
EOF
info "Or as a systemd timer, create orb-backup.service (Type=oneshot, ExecStart=$REPO_ROOT/scripts/backup.sh)"
info "plus orb-backup.timer (OnCalendar=*-*-* 02:30:00). See docs/DEPLOYMENT.md."

# ── Summary / next steps ─────────────────────────────────────────────────────
step "Install complete — next steps"
cat <<EOF

  1. Review secrets and settings:
       \$EDITOR $ENV_FILE
     For the ward, set ORB_HOST, ORB_CORS_ORIGINS and ORB_PUBLIC_APP_BASE_URL
     (docs/INSTALL_RUNBOOK.md, section 8.4). Without the last one no patient
     gets a discharge link or QR code.

  2. Ensure Ollama is running and models are pulled (for Sage/Lens/Scribe):
       ollama pull medgemma:27b
       ollama pull medgemma:4b     # cheap tier: ORB_AMBIENT_LLM_MODEL / ORB_SCRIBE_*
       ollama pull gemma3:1b
     (Without the 4B model, ambient/Scribe work falls back to the 27B model.)

  3. Sign-in account. There are NO default credentials — the admin you created
     above is the only way in. To add another later (or if you skipped it):
       set -a && . ./.env && set +a
       python server/scripts/create_admin.py

  4. Start the backend (loads .env, serves HTTPS if ORB_TLS_CERT/KEY are set):
       set -a && . ./.env && set +a
       cd server && ../server/.venv/bin/python main.py

  5. Metrics:  http://\$ORB_HOST:\$ORB_PORT/metrics   (Prometheus text format)
     Health:   http://\$ORB_HOST:\$ORB_PORT/api/health

  6. Re-running ./install.sh is safe — it preserves .env, certs, and data.

EOF
ok "Done."
