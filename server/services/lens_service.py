def image_url_for(image_path: Optional[str]) -> Optional[str]:
    """The authenticated URL a browser loads the image from, or None.

    image_path is where the file sits on the appliance's disk (absolute for an
    upload); /uploads/<name> is served by main.serve_upload, which checks the
    session and the caller's ward and audits the view."""
    name = os.path.basename(str(image_path or "").strip())
    return f"/uploads/{name}" if name else None


def decorate_analysis(row) -> dict:
    """A lens row for a clinician screen: the stored columns plus image_url.
    image_path stays for compatibility; the screen loads image_url."""
    out = dict(row)
    out["image_url"] = image_url_for(out.get("image_path"))
    return out


def get_lens_analyses(patient_id: Optional[str] = None) -> list:
    """Get lens analyses, optionally filtered by patient."""
    with db_session() as db:
        if patient_id:
            rows = db.execute(
                "SELECT * FROM lens_analyses WHERE patient_id = ? ORDER BY created_at DESC",
                (patient_id,),
            ).fetchall()
        else:
            rows = db.execute(
                "SELECT * FROM lens_analyses ORDER BY created_at DESC LIMIT 50"
            ).fetchall()
    return [decorate_analysis(r) for r in rows]
