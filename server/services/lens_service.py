# A Lens row holds the model's raw read in `analysis`. It reaches a patient's
# record only through the assign route, which stores the text the clinician
# confirmed in `reviewed_text` with who and when. Every reader outside the
# clinician's own chart (Sage, the discharge timeline, the patient portal) uses
# this filter and `reviewed_text`, never `analysis`. Image type 'lab' rows are
# the lab bot's copies of lab reports, not images, and are never imaging.
REVIEWED_IMAGING_SQL = (
    "reviewed_at IS NOT NULL AND TRIM(COALESCE(reviewed_text, '')) != '' "
    "AND COALESCE(image_type, '') != 'lab'"
)

