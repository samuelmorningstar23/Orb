"""Ward-round order wordings and the reads that share their words: the corpus for
`sage_service.detect_mutation_intent`, Sage's pre-model order gate.

WHY IT EXISTS. On 9 October 2026 the gate was measured missing most of the ways a
doctor types an order on a round: bed first ("bed 13 give lasix 40 iv"), drug
first with no verb ("inj lasix 40 iv stat"), Hinglish ("lasix 40 iv de do").
On two corpora written blind by independent agents it caught 23% and 17% of
medicine orders, and on a miss the model's own prose reaches the screen ("Done.
Furosemide 40 mg IV has been given and the order is placed."). The widening was
measured against this file before Samuel ruled, and his three rulings of that
day are what the rows below expect:

  1. Build the widening (patient reference, prescription line, ward vocabulary,
     Hinglish).
  2. A bare prescription line with no verb ("bed 13 lasix 40 iv bd") is an order.
  3. A message ending in "?" is a question unless it is polite ("please",
     "can you"). This reverses the 31 July 2026 rule that "stop the heparin?" is
     a terse order: in both blind sets 10 of 10 such messages were questions and
     0 of 300 orders ended in "?".

WHERE EACH SET CAME FROM.
  * HAND_ORDERS / HAND_READS: written for the measurement, deliberately weighted
    to the hard forms. Tuned against, so they are not evidence of recall.
  * REVIEWER_*: the bed locator reviewers' realistic ward questions and orders
    (reviews 3 to 13, numbered ward and GM codes), read out of their probes in
    docs/archive/bed-locator-attempt*. Lab and procedure requests ("repeat cbc",
    "send blood cultures") are kept apart: by the 2026-09-07 ruling they are
    work requests, outside this gate.
  * HELDOUT1_* / HELDOUT2_*: written blind by two agents that never saw the gate.
    Set 1 scored the first prototype (73% orders, no new false positive), set 2
    the second (68% orders, one new false positive, "augmentin iv dose"). Both
    were then used to fix generic gaps, so neither is held out any more; a third
    blind set validated the build (docs/SAGE_ORDER_GATE_2026-10-09.md).
  * REPORT_WRAPPERS: every verbless order line wrapped in a report or a question.
    A prescription-line rule is only safe if one report word stops it.

WHEN YOU ADD A ROW, run the gate and put the row where its verdict belongs; a
row whose expectation was guessed makes the suite agree with the guess.
"""


