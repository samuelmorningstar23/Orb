/**
 * Orb Hospital OS — I-PASS Shift-Handoff API
 *
 * Auto-draft, save, and list structured I-PASS handoffs assembled from the last
 * ~12h of a patient's data. Routed through the shared apiFetch wrapper so it
 * reuses the centralized auth headers and 401/403 handling.
 */
import { apiFetch } from './client';

export interface IpassMedication {
  drug_name: string | null;
  dosage: string | null;
  route: string | null;
  frequency: string | null;
  /** AI-extracted or agentic, and no pharmacist has verified it. */
  unverified?: boolean;
  /** The order is on hold: charted, not being given. Absent otherwise. */
  on_hold?: boolean;
  /** When it was held (UTC, format with formatClinicalDateTime). */
  held_at?: string | null;
  /** Why it was held, as the prescriber wrote it. */
  hold_reason?: string | null;
  /** The printed sheet's wording, in ward time. The screen formats held_at itself. */
  hold_label?: string;
}

export interface IpassBundle {
  /** The storage key ('sepsis6'). Never shown: bundle_label is the name. */
  bundle_type: string | null;
  /** What the sheet calls it ("Sepsis Six"). */
  bundle_label?: string | null;
  compliance_pct: number | null;
  completion_pct: number | null;
  outstanding: string[];
}

export interface IpassLatestVitals {
  timestamp: string | null;
  heart_rate: number | null;
  systolic_bp: number | null;
  diastolic_bp: number | null;
  spo2: number | null;
  temperature: number | null;
  respiratory_rate: number | null;
  consciousness: string | null;
}

/** One step Sage suggested. Nothing here has been ordered, charted or given. */
export interface IpassAssessmentConsideration {
  step: string | null;
  why: string | null;
  /** True when Orb has a one-click card queued for this step. Still does
   *  nothing until a clinician approves it. */
  orb_can_act?: boolean;
}

export interface IpassAssessmentEvidence {
  title: string | null;
  source?: string | null;
}

/**
 * TIER 3 — the four-section assessment Sage wrote, carried onto a surface where
 * a clinician is REVIEWING rather than reacting (the handover sheet and the
 * ward round). Never generated by the read; always a draft that already exists.
 *
 * ═══ EVERY LABEL IN HERE IS THE SERVER'S AND IS PRINTED AS GIVEN ═══
 * `heading`, `label` and `disclaimer` are medico-legal labelling — the property
 * that stops a reader mistaking this for something a clinician wrote — and the
 * server keeps them as constants (`ipass_service.AI_SUPPLEMENT_*`) precisely so
 * the printed sheet, the saved note and any screen cannot word them
 * differently. A client that rewrites, shortens or "improves" one of them has
 * broken the safety property, so this client renders them verbatim and has no
 * fallback string of its own for any of them.
 *
 * The same rule applies one level down: every machine enum arrives with a
 * `*_display` twin already phrased for a ward (`state_display`,
 * `age_display`, `citation_display`, `confidence_display`, `news2_context`).
 * Match on the raw enum if you must; PRINT the twin.
 */
export interface IpassReasonedAssessment {
  available: true;
  ai_drafted: true;
  authored_by: string;
  /** "AI-drafted by Orb Sage, not written by a clinician". Print verbatim. */
  label: string;
  /** "SUPPLEMENT — AI-DRAFTED ASSESSMENT (NOT WRITTEN BY A CLINICIAN)". Verbatim. */
  heading: string;
  /** The no-clinical-authority sentence. Verbatim — never reworded client-side. */
  disclaimer: string;

  assessment_id: string | null;
  reused: boolean;
  /** Raw enum: `drafted_for_vigil_alert` | `drafted_for_review`. */
  reuse_basis: string;
  /** The server's phrasing for `reuse_basis`. Print this. */
  reuse_basis_display: string;
  drafted_at: string | null;
  drafted_at_display: string | null;
  age_minutes: number | null;
  age_display: string;
  stale_after_hours: number;

  /** Raw enum: `ready` | `approved`. */
  state: string;
  state_display: string;
  /** Named clinician who endorsed it, or null when nobody has read it. */
  endorsed_by: string | null;
  endorsed_at: string | null;

  news2_at_drafting: number | null;
  news2_level_at_drafting: string | null;
  /** THE SNAPSHOT SENTENCE. This assessment describes a moment, not now. */
  news2_context: string;

  whats_happening: string;
  considerations: IpassAssessmentConsideration[];
  watch_items: string[];
  evidence: IpassAssessmentEvidence[];
  citation_basis: string | null;
  citation_display: string;
  confidence: string | null;
  confidence_display: string;
  model: string | null;
}

/** GET /ipass/{id}/reasoned-assessment — the ward round's read. */
export interface IpassReasonedAssessmentResponse {
  patient_id: string;
  /** Null whenever there is nothing honest to show — including while one is
   *  still being written. The surface renders NOTHING in that case: no heading,
   *  no "unavailable" chip, no spinner. */
  assessment: IpassReasonedAssessment | null;
  stale_after_hours: number;
  /** The print/copy form. "" when there is nothing — never a heading alone. */
  plain_text: string;
}

/** POST /ipass/{id}/reasoned-assessment/prepare — ask early, read later. */
export interface IpassPrepareResponse {
  status: 'ready' | 'preparing' | 'unavailable';
  assessment: IpassReasonedAssessment | null;
  stale_after_hours: number;
  reason: string | null;
  message: string | null;
}

export interface IpassSections {
  /** Every value null (and `text` null) while scoring is switched off on this
   *  computer: the draft then carries no severity line. */
  illness_severity: {
    severity: string | null;
    news2: number | null;
    news2_level: string | null;
    scoring_model: string | null;
    /** 2 when the patient is scored on SpO2 Scale 2 (COPD, target 88–92%);
     *  1, null or absent means Scale 1. */
    spo2_scale?: number | null;
    drivers: string[];
    text: string | null;
  };
  patient_summary: {
    name: string | null;
    mrn: string | null;
    age: number | null;
    sex: string | null;
    ward: string | null;
    bed: string | null;
    diagnosis: string | null;
    problems: string[];
    allergies: string[];
    text: string;
  };
  action_list: {
    active_medications: IpassMedication[];
    open_care_bundles: IpassBundle[];
    outstanding_items: string[];
  };
  situation_awareness: {
    /** Raw enum, e.g. `insufficient_data`. Match on this; do not print it. */
    trend: string;
    /** The server's clinical phrasing for `trend`. Print this. */
    trend_display?: string;
    trend_detail: string;
    active_deterioration: boolean;
    latest_vitals: IpassLatestVitals;
    readings_count: number;
    contingencies: string[];
    text: string;
  };
  synthesis: {
    read_back_required: boolean;
    confirmed: boolean;
    text: string;
  };
  /** Sage's four-section assessment, or null. ALWAYS PRESENT AS A KEY, so the
   *  client tests one field instead of inferring from absence — and renders
   *  nothing at all, not an empty heading, when it is null. */
  ai_assessment: IpassReasonedAssessment | null;
}

export interface IpassDraft {
  patient_id: string;
  generated_at: string;
  window_hours: number;
  source_summary: string;
  sections: IpassSections;
  plain_text: string;
}

export interface IpassHandoffRecord {
  id: number;
  patient_id: string;
  author_id: string;
  /** Null only when the author's user row is gone. */
  author_name?: string | null;
  raw_transcript: string;
  structured_note: string;
  note_format: string;
  status: string;
  /** Bare "YYYY-MM-DD HH:MM:SS" UTC (scribe_notes default): read with parseUTC. */
  created_at: string;
}

/** Auto-draft an I-PASS handoff from the patient's last ~12h of data. */
export async function getIpassDraft(patientId: string): Promise<IpassDraft> {
  return apiFetch(`/ipass/${patientId}/draft`);
}

/** Persist an I-PASS handoff draft as a scribe note (note_format='handoff'). */
export async function saveIpass(
  patientId: string,
  content: IpassDraft,
): Promise<{ id: number; status: string; note_format: string }> {
  return apiFetch(`/ipass/${patientId}/save`, {
    method: 'POST',
    body: JSON.stringify({ content }),
  });
}

/** List recent I-PASS handoff notes for a patient. */
export async function getRecentHandoffs(patientId: string): Promise<IpassHandoffRecord[]> {
  const res = await apiFetch<{ handoffs: IpassHandoffRecord[] }>(`/ipass/${patientId}/recent`);
  return res.handoffs;
}

/**
 * Read Sage's four-section assessment for this patient, or nothing.
 *
 * A PURE DB READ — no model call, milliseconds however slow the appliance is.
 * It only ever RETURNS a draft; asking for one is `prepareReasonedAssessment`,
 * made earlier so that nobody is ever waiting on this call.
 *
 * The handover sheet does not need this: `getIpassDraft` already carries the
 * same block on `sections.ai_assessment`, from the same builder, so the round
 * and the handover cannot show two versions of the machine's opinion. This
 * exists for the ward round, which assembles no handover sheet.
 */
export async function getReasonedAssessment(
  patientId: string,
): Promise<IpassReasonedAssessmentResponse> {
  return apiFetch(`/ipass/${patientId}/reasoned-assessment`);
}

/**
 * Ask Sage for the assessment EARLY, and return at once. NEVER WAITS.
 *
 * Generation is ~46 s, which is why the asking and the reading are different
 * moments: the handover is composed ahead of the change-over and the round can
 * prepare a patient while the clinician is still at the previous bed. Fire it
 * and forget it — the result is read later through the ordinary read above.
 *
 * NEEDS `sage.query` ON TOP of the read's own permission: reading a draft Sage
 * already wrote is part of seeing the chart, but spending the appliance's GPU
 * to write a new one is USING Sage, and the two are separate grants. Doctors
 * and nurses hold both today; a role that gains handover access without
 * `sage.query` would read assessments and never start one, and that is the
 * intended shape rather than a bug. Callers must therefore treat a rejection as
 * ordinary and silent — failing to start an optional second opinion nobody
 * asked for is not something to put in front of a clinician mid-round.
 */
export async function prepareReasonedAssessment(
  patientId: string,
): Promise<IpassPrepareResponse> {
  return apiFetch(`/ipass/${patientId}/reasoned-assessment/prepare`, { method: 'POST' });
}
