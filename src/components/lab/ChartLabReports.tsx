/**
 * The laboratory's reports in the chart's Labs dialog (lis-14, HIS wave 8).
 *
 * While Orb's laboratory is on or draining, the Labs dialog on a Vigil chart
 * lists every report the laboratory holds for this patient (GET
 * /api/lab/reports/patient/{id}, ward-scoped and audited on the server),
 * above the results filed in the chart. Opening one shows the report as it
 * prints (LabReportPrintView, drawn inline): released values only, 'Pending'
 * for a test not yet authorised, the range snapshot taken at entry, every
 * earlier version of an amended result and the Simulated label. Printing asks
 * the server for the print copy (audited as a print) and opens the print
 * dialog on that copy alone.
 *
 * Every read is audited, so the list loads once when the dialog opens and a
 * report loads when it is opened; nothing polls. An account the laboratory
 * does not answer (403), or a laboratory that is switched off (404), shows no
 * section at all; any other failure is said in words with a way to try again,
 * never drawn as an empty list.
 */
import { useCallback, useEffect, useMemo, useState } from 'react'
import { createPortal } from 'react-dom'

import { toLabError } from '../../api/lab'
import {
  getLabReport,
  listPatientLabReports,
  printLabReport,
  type LabReport,
  type ReportSummary,
} from '../../api/lab/reports'
import { formatAccession } from '../../api/lab/specimens'
import { formatClinicalDateTime, matchesDateSearch, parseDateSearch } from '../../lib/datetime'
import Icon from '../common/Icon'
import LabReportPrintView from '../print/LabReportPrintView'

interface ChartLabReportsProps {
  patientId: string
  /** The dialog's search box: keyword or a date such as "1 Oct 2026". */
  query: string
  /** How many laboratory reports are listed, for the dialog's count. */
  onCount?: (count: number) => void
  /** True while one report is open, so the dialog can hide its other list. */
  onOpenChange?: (open: boolean) => void
}

type ListState =
  | { state: 'loading' }
  | { state: 'hidden' }
  | { state: 'failed'; message: string }
  | { state: 'ready'; reports: ReportSummary[]; cap: number }

type OpenState =
  | { state: 'closed' }
  | { state: 'loading'; accession: string }
  | { state: 'failed'; accession: string; message: string }
  | { state: 'ready'; report: LabReport }

const SECTION_TITLE_STYLE = {
  margin: '4px 0 0', fontSize: '0.78rem', fontWeight: 600, color: 'var(--text-secondary)',
} as const

const NOTE_STYLE = { margin: 0, fontSize: '0.8rem', color: 'var(--text-muted)' } as const

function reportWhen(report: ReportSummary): string | null {
  return report.last_reported_at || report.reported_at || report.collected_at
}

function matches(report: ReportSummary, query: string): boolean {
  const q = query.trim().toLowerCase()
  if (!q) return true
  const date = parseDateSearch(query)
  if (date && matchesDateSearch(reportWhen(report), date)) return true
  const text = [
    report.tests.join(' '),
    report.accession,
    formatAccession(report.accession),
    report.status_text,
    report.specimen_type ?? '',
    formatClinicalDateTime(reportWhen(report)),
  ].join(' ').toLowerCase()
  return text.includes(q)
}

function pendingWords(count: number): string {
  return count === 1 ? '1 test pending' : `${count} tests pending`
}

function flaggedWords(count: number): string {
  return count === 1 ? '1 result flagged' : `${count} results flagged`
}

function SimulatedChip() {
  return (
    <span
      role="note"
      title="This result was generated by the simulator. It is not from this patient."
      style={{ display: 'inline-flex', alignItems: 'center', padding: '1px 8px', borderRadius: 999, fontSize: '0.68rem', fontWeight: 600, color: 'var(--status-warn-text)', border: '1px solid var(--status-warn)', background: 'var(--bg-glass)', whiteSpace: 'nowrap' }}
    >
      Simulated
    </span>
  )
}

export default function ChartLabReports({ patientId, query, onCount, onOpenChange }: ChartLabReportsProps) {
  const [list, setList] = useState<ListState>({ state: 'loading' })
  const [attempt, setAttempt] = useState(0)
  const [open, setOpen] = useState<OpenState>({ state: 'closed' })
  const [printing, setPrinting] = useState<LabReport | null>(null)
  const [printBusy, setPrintBusy] = useState(false)
  const [printError, setPrintError] = useState<string | null>(null)

  useEffect(() => {
    let live = true
    listPatientLabReports(patientId).then(
      (out) => {
        if (live) setList({ state: 'ready', reports: out.reports, cap: out.cap })
      },
      (err: unknown) => {
        if (!live) return
        const failure = toLabError(err)
        if (failure.isModuleDisabled || failure.isForbidden || failure.status === 404) {
          setList({ state: 'hidden' })
          return
        }
        setList({ state: 'failed', message: failure.message || 'The laboratory reports could not be loaded.' })
      },
    )
    return () => { live = false }
  }, [patientId, attempt])

  const shown = useMemo(
    () => (list.state === 'ready' ? list.reports.filter((r) => matches(r, query)) : []),
    [list, query],
  )

  useEffect(() => {
    onCount?.(list.state === 'ready' ? list.reports.length : 0)
  }, [list, onCount])

  useEffect(() => {
    onOpenChange?.(open.state !== 'closed')
  }, [open.state, onOpenChange])

  const openReport = useCallback(async (accession: string) => {
    setPrintError(null)
    setOpen({ state: 'loading', accession })
    try {
      setOpen({ state: 'ready', report: await getLabReport(accession) })
    } catch (err) {
      const failure = toLabError(err)
      setOpen({
        state: 'failed',
        accession,
        message: failure.isNotFound
          ? 'This report is no longer available to this account.'
          : (failure.message || 'The report could not be opened.'),
      })
    }
  }, [])

  const print = async () => {
    if (open.state !== 'ready' || printBusy) return
    setPrintBusy(true)
    setPrintError(null)
    try {
      setPrinting(await printLabReport(open.report.accession))
    } catch (err) {
      setPrintError(toLabError(err).message || 'The report could not be printed.')
    } finally {
      setPrintBusy(false)
    }
  }

  if (list.state === 'hidden') return null

  if (open.state !== 'closed') {
    const accession = open.state === 'ready' ? open.report.accession : open.accession
    return (
      <section aria-label={`Laboratory report ${formatAccession(accession)}`}
        style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
        <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap' }}>
          <button type="button" className="modal__btn modal__btn--ghost" style={{ padding: '8px 16px', borderRadius: 8 }}
            onClick={() => { setOpen({ state: 'closed' }); setPrintError(null) }}>
            Back to the list
          </button>
          {open.state === 'ready' && (
            <button type="button" className="modal__confirm"
              onClick={() => void print()} disabled={printBusy}>
              {printBusy ? 'Preparing the print' : 'Print report'}
            </button>
          )}
        </div>
        {open.state === 'loading' && <p style={NOTE_STYLE} role="status">Opening the report</p>}
        {open.state === 'failed' && <p style={{ ...NOTE_STYLE, color: 'var(--status-danger-text)' }} role="alert">{open.message}</p>}
        {printError && <p style={{ ...NOTE_STYLE, color: 'var(--status-danger-text)' }} role="alert">{printError}</p>}
        {open.state === 'ready' && (
          <div style={{ maxHeight: '56vh', overflowY: 'auto' }}>
            <LabReportPrintView report={open.report} variant="screen" autoPrint={false} />
          </div>
        )}
        {printing && createPortal(
          <LabReportPrintView report={printing} onAfterPrint={() => setPrinting(null)} />,
          document.body,
        )}
      </section>
    )
  }

  return (
    <section aria-labelledby="chart-lab-reports-title" style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
      <h3 id="chart-lab-reports-title" style={SECTION_TITLE_STYLE}>From the laboratory</h3>
      {list.state === 'loading' && <p style={NOTE_STYLE} role="status">Loading the laboratory reports</p>}
      {list.state === 'failed' && (
        <div role="alert" style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
          <p style={{ ...NOTE_STYLE, color: 'var(--status-danger-text)' }}>{list.message}</p>
          <button type="button" className="modal__btn modal__btn--ghost" style={{ padding: '6px 12px', borderRadius: 8 }}
            onClick={() => { setList({ state: 'loading' }); setAttempt((n) => n + 1) }}>
            Try again
          </button>
        </div>
      )}
      {list.state === 'ready' && list.reports.length === 0 && (
        <p style={NOTE_STYLE}>The laboratory has no report for this patient.</p>
      )}
      {list.state === 'ready' && list.reports.length > 0 && shown.length === 0 && (
        <p style={NOTE_STYLE}>No laboratory report matches your search.</p>
      )}
      {shown.length > 0 && (
        <div className="reports-modal__list" style={{ maxHeight: 240 }}>
          {shown.map((r) => (
            <button
              type="button"
              key={r.accession}
              className="reports-modal__card"
              aria-label={`Open laboratory report ${formatAccession(r.accession)}`}
              onClick={() => void openReport(r.accession)}
            >
              <span className="reports-modal__card-icon reports-modal__card-icon--lab" aria-hidden>
                <Icon name="flask" size={18} />
              </span>
              <span className="reports-modal__card-body">
                <span className="reports-modal__card-header">
                  <span className="reports-modal__card-type">{r.tests.join(', ') || 'Laboratory report'}</span>
                  {r.simulated && <SimulatedChip />}
                  <span className="reports-modal__card-date">{formatClinicalDateTime(reportWhen(r))}</span>
                </span>
                <span className="reports-modal__card-preview">
                  {[
                    r.status_text,
                    `Accession ${formatAccession(r.accession)}`,
                    r.specimen_type,
                    r.pending_count > 0 ? pendingWords(r.pending_count) : null,
                    r.flagged_count > 0 ? flaggedWords(r.flagged_count) : null,
                  ].filter(Boolean).join(' · ')}
                </span>
              </span>
            </button>
          ))}
        </div>
      )}
      {list.state === 'ready' && list.reports.length >= list.cap && (
        <p style={NOTE_STYLE}>Showing the latest {list.cap} reports.</p>
      )}
    </section>
  )
}
