/**
 * The laboratory report print (lis-14). What it must never get wrong:
 *
 *   · The range printed is the snapshot the server sent with the result, never
 *     anything the screen works out.
 *   · An amended result prints its earlier version, who replaced it and why.
 *   · A test not yet released prints 'Pending' and no value; a withdrawn
 *     result prints that it was withdrawn and never its value.
 *   · A simulated result carries the Simulated label.
 *   · The signatory prints with the registration number, or says it is not on
 *     file.
 *   · Times print through the clinical date helpers; no em dash anywhere.
 *   · The print dialog opens only for the print copy, never for the preview.
 */
import { render, screen, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import type { LabReport, ReportItem } from '../../api/lab/reports'
import { formatClinicalDateTime } from '../../lib/datetime'
import LabReportPrintView from './LabReportPrintView'

const SIGNATORY = { name: 'Dr Meera Rao', registration_number: 'KMC-4521', registration_text: 'KMC-4521' }

function item(over: Partial<ReportItem> = {}): ReportItem {
  return {
    item_id: 1,
    order_id: 'O-1',
    test: { id: 'LOINC:2823-3', name: 'Potassium', short_name: 'K', result_type: 'numeric' },
    panel_name: 'Renal function panel',
    section_id: 'biochemistry',
    section_name: 'Biochemistry',
    state: 'reported',
    state_text: 'Reported',
    result: {
      id: 41, version: 1, value_text: '5.6', comparator: null, unit: 'mmol/L',
      abnormal_flag: 'H', flag_text: 'High', is_critical: 0,
      reference_range_text: '3.5 to 5.1 mmol/L', range_applies: true,
      comment: null, amend_reason: null, reported_at: '2026-10-09T05:10:00+00:00',
      authorised_by: SIGNATORY, checked_by: { name: 'Anil Kumar' },
      checked_at: '2026-10-09T05:00:00+00:00', simulated: false,
    },
    history: [],
    amended: false,
    cancelled: null,
    ...over,
  }
}

function report(over: Partial<LabReport> = {}): LabReport {
  return {
    accession: '261009000127',
    status: 'final',
    status_text: 'Final report',
    amended: false,
    simulated: false,
    pending_count: 0,
    patient: { id: 'P1', name: 'Asha Menon', mrn: 'MRN-0042', sex_text: 'Female',
      age_text: '46 years', ward: 'GM-1', bed: '4A', department: 'General Medicine',
      discharged: false },
    specimen: { type: 'Serum', container: 'Gold top (SST)', priority: 'routine',
      priority_text: 'Routine', status: 'completed',
      collected_at: '2026-10-09T03:30:00+00:00', collected_by: { name: 'Sunita' },
      collection_location: null, received_at: '2026-10-09T03:50:00+00:00',
      received_by: { name: 'Anil Kumar' } },
    requested_by: [{ name: 'Dr Arjun Shah' }],
    reported_at: '2026-10-09T05:10:00+00:00',
    last_reported_at: '2026-10-09T05:10:00+00:00',
    items: [item()],
    signatories: [SIGNATORY],
    technologists: [{ name: 'Anil Kumar' }],
    notes: ['Each reference range is the one in force when the result was entered.'],
    simulated_text: 'Simulated result: generated by the simulator, not from this patient.',
    ...over,
  }
}

let print: ReturnType<typeof vi.spyOn>

beforeEach(() => {
  print = vi.spyOn(window, 'print').mockImplementation(() => {})
})
afterEach(() => {
  print.mockRestore()
})

function row(name: string): HTMLElement {
  const cell = screen.getByText(name, { selector: 'td.lab-report__test' })
  return cell.closest('tr') as HTMLElement
}

describe('LabReportPrintView', () => {
  it('prints the patient, the sample and the result with the range snapshot', () => {
    render(<LabReportPrintView report={report()} autoPrint={false} />)
    expect(screen.getByText('Laboratory report')).toBeTruthy()
    expect(screen.getByText('Final report')).toBeTruthy()
    expect(screen.getByText('261009 00012 7')).toBeTruthy()
    expect(screen.getByText('Asha Menon')).toBeTruthy()
    expect(screen.getByText('MRN-0042')).toBeTruthy()
    expect(screen.getByText('46 years')).toBeTruthy()
    const potassium = row('Potassium')
    expect(within(potassium).getByText('5.6 mmol/L')).toBeTruthy()
    expect(within(potassium).getByText('High')).toBeTruthy()
    expect(within(potassium).getByText('3.5 to 5.1 mmol/L')).toBeTruthy()
    expect(screen.getByText('Biochemistry')).toBeTruthy()
    expect(screen.getByText('Renal function panel')).toBeTruthy()
  })

  it('prints the times through the clinical date helpers', () => {
    render(<LabReportPrintView report={report()} autoPrint={false} />)
    const collected = formatClinicalDateTime('2026-10-09T03:30:00+00:00')
    expect(screen.getByText(`${collected}, by Sunita`)).toBeTruthy()
  })

  it('prints an amended result with its earlier version, who replaced it and why', () => {
    const amended = item({
      amended: true,
      result: { ...item().result!, id: 42, version: 2, value_text: '4.6', flag_text: '',
        abnormal_flag: '', amend_reason: 'Haemolysed sample, repeated' },
      history: [{
        version: 1, state: 'replaced', value_text: '5.6', unit: 'mmol/L', flag_text: 'High',
        reference_range_text: '3.5 to 5.1 mmol/L', reported_at: '2026-10-09T05:10:00+00:00',
        reported_by: { name: 'Dr Meera Rao' }, ended_at: '2026-10-09T07:00:00+00:00',
        ended_by: { name: 'Dr Kiran Das' }, reason: 'Haemolysed sample, repeated',
      }],
    })
    render(<LabReportPrintView report={report({ status: 'amended', status_text: 'Amended report',
      amended: true, items: [amended] })} autoPrint={false} />)
    expect(screen.getByText('Amended report')).toBeTruthy()
    expect(within(row('Potassium')).getByText('4.6 mmol/L')).toBeTruthy()
    expect(screen.getByText(/Amended, version 2: Haemolysed sample, repeated/)).toBeTruthy()
    const history = screen.getByText(/Version 1, reported/)
    expect(history.textContent).toContain('5.6 mmol/L, High')
    expect(history.textContent).toContain('Replaced')
    expect(history.textContent).toContain('by Dr Kiran Das')
    expect(history.textContent).toContain('Reason: Haemolysed sample, repeated')
  })

  it('prints a pending test as pending with no value, and says the report is interim', () => {
    const pending = item({ item_id: 2, test: { id: 'LOINC:2951-2', name: 'Sodium', short_name: 'Na',
      result_type: 'numeric' }, state: 'pending', state_text: 'Pending', result: null })
    render(<LabReportPrintView report={report({ status: 'interim',
      status_text: 'Interim report: 1 test not yet reported', pending_count: 1,
      items: [item(), pending] })} autoPrint={false} />)
    expect(screen.getByText('Interim report: 1 test not yet reported')).toBeTruthy()
    const sodium = row('Sodium')
    expect(within(sodium).getByText('Pending')).toBeTruthy()
    expect(sodium.querySelector('.lab-report__flag')?.textContent).toBe('')
    expect(sodium.querySelector('.lab-report__range')?.textContent).toBe('')
  })

  it('prints a withdrawn result without its value', () => {
    const withdrawn = item({ state: 'withdrawn', state_text: 'Withdrawn', result: null, amended: true,
      history: [{ version: 1, state: 'withdrawn', value_text: null, unit: null, flag_text: '',
        reference_range_text: null, reported_at: '2026-10-09T05:10:00+00:00',
        reported_by: { name: 'Dr Meera Rao' }, ended_at: '2026-10-09T06:00:00+00:00',
        ended_by: { name: 'Dr Meera Rao' }, reason: 'Entered on the wrong patient' }] })
    const { container } = render(<LabReportPrintView report={report({ status: 'amended',
      status_text: 'Amended report', amended: true, items: [withdrawn] })} autoPrint={false} />)
    expect(within(row('Potassium')).getByText('Withdrawn')).toBeTruthy()
    expect(screen.getByText(/Withdrawn on .* by Dr Meera Rao\. Reason: Entered on the wrong patient/))
      .toBeTruthy()
    expect(container.textContent).not.toContain('5.6')
  })

  it('prints an amended then withdrawn result with no earlier value, only who and when', () => {
    const withdrawn = item({ state: 'withdrawn', state_text: 'Withdrawn', result: null, amended: true,
      history: [
        { version: 1, state: 'replaced', value_withheld: true, value_text: null, unit: null,
          flag_text: '', reference_range_text: null, reported_at: '2026-10-09T05:10:00+00:00',
          reported_by: { name: 'Dr Meera Rao' }, ended_at: '2026-10-09T05:40:00+00:00',
          ended_by: { name: 'Dr Kiran Das' }, reason: null },
        { version: 2, state: 'withdrawn', value_withheld: true, value_text: null, unit: null,
          flag_text: '', reference_range_text: null, reported_at: '2026-10-09T05:40:00+00:00',
          reported_by: { name: 'Dr Kiran Das' }, ended_at: '2026-10-09T06:00:00+00:00',
          ended_by: { name: 'Dr Kiran Das' }, reason: 'Belonged to another patient' },
      ] })
    const { container } = render(<LabReportPrintView report={report({ status: 'amended',
      status_text: 'Amended report', amended: true, items: [withdrawn] })} autoPrint={false} />)
    const first = screen.getByText(/Version 1, reported/)
    const replaced = formatClinicalDateTime('2026-10-09T05:40:00+00:00')
    expect(first.textContent).toBe(
      `Version 1, reported ${formatClinicalDateTime('2026-10-09T05:10:00+00:00')} by Dr Meera Rao. `
      + `Replaced on ${replaced} by Dr Kiran Das.`)
    expect(first.textContent).not.toContain('no value')
    expect(first.textContent).not.toContain('Reason')
    expect(screen.getByText(/Version 2, reported .* Withdrawn on .* by Dr Kiran Das\. Reason: Belonged to another patient/))
      .toBeTruthy()
    expect(container.textContent).not.toContain('mmol/L')
  })

  it('labels a simulated result', () => {
    const simulated = item({ result: { ...item().result!, simulated: true } })
    render(<LabReportPrintView report={report({ simulated: true, items: [simulated] })}
      autoPrint={false} />)
    expect(screen.getByText('Simulated result: generated by the simulator, not from this patient.'))
      .toBeTruthy()
    expect(within(row('Potassium')).getByText('Simulated')).toBeTruthy()
  })

  it('prints the signatory with the registration number, or says it is not on file', () => {
    const { rerender } = render(<LabReportPrintView report={report()} autoPrint={false} />)
    expect(screen.getByText(/Dr Meera Rao, KMC-4521/)).toBeTruthy()
    rerender(<LabReportPrintView report={report({ signatories: [{ name: 'Dr Kiran Das',
      registration_number: null, registration_text: 'Registration number not on file' }] })}
    autoPrint={false} />)
    expect(screen.getByText(/Dr Kiran Das, Registration number not on file/)).toBeTruthy()
  })

  it('says a coded result has no range and an unconfigured one says so', () => {
    const coded = item({ item_id: 3, test: { id: 'LOCAL:HBS', name: 'HBsAg', short_name: 'HBsAg',
      result_type: 'coded' }, result: { ...item().result!, value_text: 'Non-reactive', unit: null,
      flag_text: '', reference_range_text: null, range_applies: false } })
    const unranged = item({ item_id: 4, test: { id: 'LOCAL:ALB', name: 'Albumin', short_name: 'Alb',
      result_type: 'numeric' }, result: { ...item().result!, flag_text: '',
      reference_range_text: null, range_applies: true } })
    render(<LabReportPrintView report={report({ items: [coded, unranged] })} autoPrint={false} />)
    expect(within(row('HBsAg')).getByText('Not applicable')).toBeTruthy()
    expect(within(row('Albumin')).getByText('Reference range not configured')).toBeTruthy()
  })

  it('has no em dash anywhere', () => {
    const { container } = render(<LabReportPrintView report={report({
      printed_at: '2026-10-09T08:00:00+00:00', printed_by: { name: 'Anil Kumar' },
      hospital: { name: 'City Hospital' } })} autoPrint={false} />)
    expect(container.textContent).not.toContain(String.fromCharCode(0x2014))
    expect(screen.getByText('City Hospital')).toBeTruthy()
    expect(screen.getByText(/Printed .* by Anil Kumar/)).toBeTruthy()
  })

  it('opens the print dialog for the print copy only', async () => {
    const { unmount } = render(<LabReportPrintView report={report()} variant="screen" />)
    await new Promise((r) => setTimeout(r, 50))
    expect(print).not.toHaveBeenCalled()
    unmount()
    render(<LabReportPrintView report={report()} />)
    await new Promise((r) => setTimeout(r, 50))
    expect(print).toHaveBeenCalledTimes(1)
  })

  it('marks the preview so paper prints only the portal copy', () => {
    const { container } = render(<LabReportPrintView report={report()} variant="screen" />)
    expect(container.querySelector('.lab-report-print-layout--screen')).toBeTruthy()
  })
})
