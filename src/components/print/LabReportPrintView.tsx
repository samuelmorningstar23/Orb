import { formatAccession } from '../../api/lab/specimens'
import {
  reportValueText,
  type LabReport,
  type ReportItem,
  type ReportPerson,
  type ReportVersion,
} from '../../api/lab/reports'
import { formatClinicalDateTime } from '../../lib/datetime'
import { usePrintOnce } from './usePrintOnce'

/**
 * The laboratory report of one sample (lis-14), on A4.
 *
 * WHAT IT PRINTS is exactly what the server sent (GET /api/lab/reports/{n}/print,
 * audited as a print): released values only. A test the laboratory has not
 * authorised prints 'Pending' and no value; a withdrawn result prints that it
 * was withdrawn, never its value.
 *
 *   * the patient's name, UHID, age at collection and sex (no date of birth);
 *   * the sample's accession, type, priority and its collected, received and
 *     reported times in hospital time (src/lib/datetime.ts);
 *   * each test with its value (a bound keeps its comparator), unit, flag in
 *     words, the reference range SNAPSHOT taken when the result was entered,
 *     and the comment;
 *   * every earlier version of an amended result, with who replaced it, when
 *     and why, so an amended report always says it is amended; when the
 *     result was later withdrawn, each earlier version prints only who and
 *     when, never a value (the server sends none);
 *   * who checked each result and the signatories with their registration
 *     numbers ('Registration number not on file' when there is none);
 *   * the Simulated honesty label on a simulated result.
 *
 * Print-first, portaled by the caller into document.body; src/print.css hides
 * the layout on screen and reveals only it on paper. With variant 'screen' the
 * same layout draws inline as a preview and never opens the print dialog.
 */

interface LabReportPrintViewProps {
  report: LabReport
  /** Called on `afterprint`, so the caller can take the portal down. */
  onAfterPrint?: () => void
  /** Tests only: render without opening the print dialog. */
  autoPrint?: boolean
  /** 'print' (the default) portals to <body> and opens the dialog once;
   *  'screen' is an inline preview. */
  variant?: 'print' | 'screen'
}

function when(value: string | null | undefined): string {
  return formatClinicalDateTime(value) || 'Not recorded'
}

function who(person: ReportPerson | null | undefined): string {
  return person?.name ?? 'Not recorded'
}

function rangeText(item: ReportItem): string {
  const result = item.result
  if (!result) return ''
  if (result.reference_range_text) return result.reference_range_text
  return result.range_applies ? 'Reference range not configured' : 'Not applicable'
}

function versionLine(version: ReportVersion): string {
  const reported = `Version ${version.version}, reported ${when(version.reported_at)}`
    + (version.reported_by ? ` by ${version.reported_by.name}` : '')
  const ended = version.ended_at ? ` on ${when(version.ended_at)}` : ''
  const by = version.ended_by ? ` by ${version.ended_by.name}` : ''
  if (version.state === 'withdrawn') {
    return `${reported}. Withdrawn${ended}${by}.`
  }
  // A later version was withdrawn, so this one may be another patient's
  // value: the server sends none, and the paper says only who and when.
  if (version.value_withheld) return `${reported}. Replaced${ended}${by}.`
  const value = [reportValueText(version), version.flag_text].filter(Boolean).join(', ')
  return `${reported}: ${value || 'no value'}. Replaced${ended}${by}.`
}

function ResultRow({ item }: { item: ReportItem }) {
  const result = item.result
  const notes: string[] = []
  if (result?.comment) notes.push(result.comment)
  if (item.amended && result) {
    notes.push(`Amended, version ${result.version}${result.amend_reason ? `: ${result.amend_reason}` : ''}`)
  }
  if (item.state === 'cancelled' && item.cancelled?.reason) notes.push(item.cancelled.reason)
  return (
    <>
      <tr className={`lab-report__row lab-report__row--${item.state}`}>
        <td className="lab-report__test">{item.test.name}</td>
        <td className="lab-report__value">
          {result ? (
            <strong>{reportValueText(result)}</strong>
          ) : (
            <span>{item.state_text}</span>
          )}
          {result?.simulated && (
            <span className="lab-report__simulated" role="note"
              title="This result was generated by the simulator. It is not from this patient.">
              {' '}Simulated
            </span>
          )}
        </td>
        <td className="lab-report__flag">{result?.flag_text ?? ''}</td>
        <td className="lab-report__range">{rangeText(item)}</td>
        <td className="lab-report__notes">{notes.join('. ')}</td>
      </tr>
      {item.history.map((version) => (
        <tr key={`${item.item_id}-v${version.version}`} className="lab-report__history">
          <td />
          <td colSpan={4}>
            {versionLine(version)}
            {version.reason ? ` Reason: ${version.reason}` : ''}
          </td>
        </tr>
      ))}
    </>
  )
}

interface ItemGroup {
  key: string
  section: string
  /** True for the first group of its section, which prints the heading. */
  firstOfSection: boolean
  panel: string | null
  items: ReportItem[]
}

/** Tests grouped by section, then by panel, in the order the server sent. */
function groupItems(items: ReportItem[]): ItemGroup[] {
  const groups: ItemGroup[] = []
  for (const item of items) {
    const section = item.section_name ?? 'Laboratory'
    const key = `${section}|${item.panel_name ?? ''}`
    const last = groups[groups.length - 1]
    if (last && last.key === key) {
      last.items.push(item)
    } else {
      groups.push({ key, section, firstOfSection: !last || last.section !== section,
        panel: item.panel_name, items: [item] })
    }
  }
  return groups
}

export default function LabReportPrintView({
  report,
  onAfterPrint = () => {},
  autoPrint = true,
  variant = 'print',
}: LabReportPrintViewProps) {
  usePrintOnce(onAfterPrint, autoPrint && variant === 'print')

  const { patient, specimen } = report
  const where = [patient.ward, patient.bed ? `bed ${patient.bed}` : null].filter(Boolean).join(', ')
  const groups = groupItems(report.items)
  const className = variant === 'screen'
    ? 'lab-report-print-layout lab-report-print-layout--screen'
    : 'lab-report-print-layout'

  return (
    <div className={className} aria-label={`Laboratory report ${formatAccession(report.accession)}`}>
      <header className="lab-report__header">
        <div>
          {report.hospital?.name && <p className="lab-report__hospital">{report.hospital.name}</p>}
          <h1 className="lab-report__title">Laboratory report</h1>
          <p className="lab-report__status">{report.status_text}</p>
          {report.amended && report.status !== 'amended' && (
            <p className="lab-report__status">This report includes amended results.</p>
          )}
        </div>
        <div className="lab-report__accession">
          <span>Accession</span>
          <strong>{formatAccession(report.accession)}</strong>
        </div>
      </header>

      {report.simulated && (
        <p className="lab-report__simulated-note" role="note">{report.simulated_text}</p>
      )}

      <table className="lab-report__facts">
        <tbody>
          <tr>
            <th scope="row">Patient</th>
            <td>{patient.name ?? 'Not recorded'}</td>
            <th scope="row">UHID</th>
            <td>{patient.mrn ?? 'Not recorded'}</td>
          </tr>
          <tr>
            <th scope="row">Age at collection</th>
            <td>{patient.age_text}</td>
            <th scope="row">Sex</th>
            <td>{patient.sex_text}</td>
          </tr>
          <tr>
            <th scope="row">Ward</th>
            <td>{where || 'Not recorded'}</td>
            <th scope="row">Requested by</th>
            <td>{report.requested_by.map((p) => p.name).join(', ') || 'Not recorded'}</td>
          </tr>
          <tr>
            <th scope="row">Specimen</th>
            <td>{[specimen.type, specimen.container].filter(Boolean).join(', ') || 'Not recorded'}</td>
            <th scope="row">Priority</th>
            <td>{specimen.priority_text}</td>
          </tr>
          <tr>
            <th scope="row">Collected</th>
            <td>{when(specimen.collected_at)}{specimen.collected_by ? `, by ${specimen.collected_by.name}` : ''}</td>
            <th scope="row">Received</th>
            <td>{when(specimen.received_at)}{specimen.received_by ? `, by ${specimen.received_by.name}` : ''}</td>
          </tr>
          <tr>
            <th scope="row">Reported</th>
            <td>{when(report.reported_at)}</td>
            <th scope="row">Last changed</th>
            <td>{when(report.last_reported_at)}</td>
          </tr>
        </tbody>
      </table>

      <table className="lab-report__results">
        <thead>
          <tr>
            <th scope="col">Test</th>
            <th scope="col">Result</th>
            <th scope="col">Flag</th>
            <th scope="col">Reference range</th>
            <th scope="col">Notes</th>
          </tr>
        </thead>
        <tbody>
          {groups.map((group, index) => (
            <GroupRows key={`${group.key}-${index}`} section={group.firstOfSection ? group.section : null}
              panel={group.panel} items={group.items} />
          ))}
        </tbody>
      </table>

      <section className="lab-report__people">
        <p>
          <span className="lab-report__label">Checked by: </span>
          {report.technologists.map((p) => p.name).join(', ') || 'Not recorded'}
        </p>
        {report.signatories.map((person) => (
          <p key={`${person.name}-${person.registration_text}`}>
            <span className="lab-report__label">Authorised by: </span>
            {person.name}, {person.registration_text}
          </p>
        ))}
      </section>

      <footer className="lab-report__footer">
        <ul className="lab-report__notes-list">
          {report.notes.map((note) => <li key={note}>{note}</li>)}
        </ul>
        {report.printed_at && (
          <p>Printed {when(report.printed_at)}{report.printed_by ? ` by ${who(report.printed_by)}` : ''}</p>
        )}
      </footer>
    </div>
  )
}

function GroupRows({ section, panel, items }: { section: string | null; panel: string | null; items: ReportItem[] }) {
  return (
    <>
      {section && (
        <tr className="lab-report__section">
          <th scope="rowgroup" colSpan={5}>{section}</th>
        </tr>
      )}
      {panel && (
        <tr className="lab-report__panel">
          <td colSpan={5}>{panel}</td>
        </tr>
      )}
      {items.map((item) => <ResultRow key={item.item_id} item={item} />)}
    </>
  )
}
