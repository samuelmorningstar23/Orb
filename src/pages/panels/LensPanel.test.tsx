/**
 * Lens carries a fixed "investigational" label whatever the model, the stream
 * or the provenance registry does.
 *
 * The only disclaimer used to live inside the editable findings box: absent
 * before an analysis, absent when the stream failed, deletable by the clinician.
 */
import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

const api = vi.hoisted(() => ({
  analyzeLensImage: vi.fn(),
  getPatientsList: vi.fn(async () => []),
  assignLensToPatient: vi.fn(),
  // ProvenanceChip's registry fetch: refused, as on a server that is down.
  apiFetch: vi.fn(async () => { throw new Error('API 503') }),
}))
vi.mock('../../api/client', () => api)

import LensPanel from './LensPanel'
import { INVESTIGATIONAL_LEAD } from '../../components/InvestigationalBanner'
import { withoutAppendedDisclaimer } from '../../lib/lensDisclaimer'

/* The exact banner lens_service appends, as the SSE reader hands it over (the
   blank line before the rule is eaten by the event split). */
const SERVER_BANNER =
  '---\n⚠️ INVESTIGATIONAL. NOT FOR DIAGNOSTIC USE. This is an unverified, AI-assisted ' +
  'image interpretation generated by a local model that has not been clinically ' +
  'validated. It is NOT a radiologist read.'

beforeEach(() => {
  vi.stubGlobal('URL', Object.assign(URL, {
    createObjectURL: vi.fn(() => 'blob:lens-test'),
    revokeObjectURL: vi.fn(),
  }))
})

afterEach(() => {
  cleanup()
  vi.clearAllMocks()
})

function pickImage() {
  const input = document.getElementById('lens-file-input') as HTMLInputElement
  const file = new File([new Uint8Array([0xff, 0xd8, 0xff])], 'chest.jpg', { type: 'image/jpeg' })
  fireEvent.change(input, { target: { files: [file] } })
}

describe('the Lens investigational label', () => {
  it('is on screen before any image is chosen', () => {
    render(<LensPanel />)
    expect(screen.getByRole('note').textContent).toContain(INVESTIGATIONAL_LEAD)
  })

  it('does not promise CT or any format the upload refuses', () => {
    render(<LensPanel />)
    const hint = screen.getByText(/Drag and drop/)
    expect(hint.textContent).toBe('Drag and drop a JPG or PNG image, or use the button below.')
  })

  it('stays when the analysis fails and the provenance fetch fails', async () => {
    api.analyzeLensImage.mockRejectedValueOnce(new Error('model offline'))
    render(<LensPanel />)
    pickImage()
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Analyze Image' })) })
    expect(api.apiFetch).toHaveBeenCalled()
    expect(screen.getByRole('note').textContent).toContain(INVESTIGATIONAL_LEAD)
  })

  it('keeps the server banner out of the editable findings box', async () => {
    api.analyzeLensImage.mockImplementationOnce(async (_f: File, _o: unknown, onChunk: (t: string) => void) => {
      onChunk('FINDINGS:\n- Clear lungs')
      onChunk(`FINDINGS:\n- Clear lungs${SERVER_BANNER}`)
      return { text: '', analysisId: 7 }
    })
    render(<LensPanel />)
    pickImage()
    await act(async () => { fireEvent.click(screen.getByRole('button', { name: 'Analyze Image' })) })
    const box = screen.getByLabelText('Editable AI reference findings') as HTMLTextAreaElement
    expect(box.value).toBe('FINDINGS:\n- Clear lungs')
    // The label did not go with it: it is fixed text outside the box.
    expect(screen.getByRole('note').textContent).toContain(INVESTIGATIONAL_LEAD)
  })
})

describe('withoutAppendedDisclaimer', () => {
  it('cuts the banner and its rule line', () => {
    expect(withoutAppendedDisclaimer(`IMPRESSION: normal\n\n${SERVER_BANNER}`)).toBe('IMPRESSION: normal')
  })

  it('leaves text with no banner alone', () => {
    expect(withoutAppendedDisclaimer('IMPRESSION: normal\n- a - b')).toBe('IMPRESSION: normal\n- a - b')
  })
})
