/**
 * The Reports view (lis-14). What it must never get wrong:
 *
 *   · It declares itself as the reports tab, for lab.read, kept while the
 *     module drains.
 *   · Opening a report shows the report as it prints; printing asks the server
 *     for the print copy (the audited one) and prints exactly that.
 *   · A misread accession is said in words; a failed list load is never an
 *     empty list; a switched-off module goes to the panel.
 */
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { LabApiError } from '../../../api/lab'
import type { LabReport, ReportList, ReportSummary } from '../../../api/lab/reports'
import ReportsView, * as reportsModule from './ReportsView'
import { discoverViews } from './viewRegistry'

vi.mock('../../../api/lab/reports', async () => {
  const actual = await vi.importActual<typeof import('../../../api/lab/reports')>(
    '../../../api/lab/reports')
  return { ...actual, getLabReport: vi.fn(), printLabReport: vi.fn(), listLabReports: vi.fn() }
})

const api = vi.mocked(await import('../../../api/lab/reports'))

const SUMMARY: ReportSummary = {
  accession: '261009000127', status: 'final', status_text: 'Final report', amended: false,
  simulated: false, pending_count: 0,
  patient: { id: 'P1', name: 'Asha Menon', mrn: 'MRN-0042', ward: 'GM-1', bed: '4A' },
  specimen_type: 'Serum', priority: 'stat', collected_at: '2026-10-09T03:30:00+00:00',
  reported_at: '2026-10-09T05:10:00+00:00', last_reported_at: '2026-10-09T05:10:00+00:00',
  tests: ['K', 'Na'], flagged_count: 1,
}

function list(over: Partial<ReportList> = {}): ReportList {
  return { reports: [SUMMARY], day: '2026-10-09', uhid: null, cap: 200,
    scope: { department: null, hospital_wide: true }, ...over }
}

const REPORT: LabReport = {
  accession: '261009000127', status: 'final', status_text: 'Final report', amended: false,
  simulated: false, pending_count: 0,
  patient: { id: 'P1', name: 'Asha Menon', mrn: 'MRN-0042', sex_text: 'Female', age_text: '46 years',
    ward: 'GM-1', bed: '4A', department: 'General Medicine', discharged: false },
  specimen: { type: 'Serum', container: null, priority: 'stat', priority_text: 'STAT',
    status: 'completed', collected_at: '2026-10-09T03:30:00+00:00', collected_by: null,
    collection_location: null, received_at: '2026-10-09T03:50:00+00:00', received_by: null },
  requested_by: [],
  reported_at: '2026-10-09T05:10:00+00:00',
  last_reported_at: '2026-10-09T05:10:00+00:00',
  items: [{
    item_id: 1, order_id: 'O-1',
    test: { id: 'LOINC:2823-3', name: 'Potassium', short_name: 'K', result_type: 'numeric' },
    panel_name: null, section_id: 'biochemistry', section_name: 'Biochemistry',
    state: 'reported', state_text: 'Reported',
    result: { id: 41, version: 1, value_text: '5.6', comparator: null, unit: 'mmol/L',
      abnormal_flag: 'H', flag_text: 'High', is_critical: 0,
      reference_range_text: '3.5 to 5.1 mmol/L', range_applies: true, comment: null,
      amend_reason: null, reported_at: '2026-10-09T05:10:00+00:00',
      authorised_by: { name: 'Dr Meera Rao', registration_number: 'KMC-4521',
        registration_text: 'KMC-4521' }, checked_by: { name: 'Anil Kumar' },
      checked_at: null, simulated: false },
    history: [], amended: false, cancelled: null,
  }],
  signatories: [{ name: 'Dr Meera Rao', registration_number: 'KMC-4521', registration_text: 'KMC-4521' }],
  technologists: [{ name: 'Anil Kumar' }],
  notes: [],
  simulated_text: 'Simulated result: generated by the simulator, not from this patient.',
}

const props = { meta: {}, state: 'on' as const, openView: vi.fn(), onModuleOff: vi.fn() }
let print: ReturnType<typeof vi.spyOn>

beforeEach(() => {
  api.listLabReports.mockResolvedValue(list())
  print = vi.spyOn(window, 'print').mockImplementation(() => {})
})
afterEach(() => {
  vi.clearAllMocks()
  print.mockRestore()
})

describe('ReportsView', () => {
  it('declares itself to the panel as the reports tab', () => {
    const [entry] = discoverViews({ './lab/ReportsView.tsx': reportsModule })
    expect(entry).toMatchObject({ id: 'reports', label: 'Reports', order: 70,
      permission: 'lab.read', whenDraining: 'show' })
  })

  it('lists the samples reported today and opens one', async () => {
    api.getLabReport.mockResolvedValue(REPORT)
    render(<ReportsView {...props} />)
    const table = await screen.findByRole('table')
    expect(within(table).getByText('Asha Menon')).toBeTruthy()
    expect(within(table).getByText('K, Na')).toBeTruthy()
    fireEvent.click(within(table).getByRole('button', { name: 'Open report 261009 00012 7' }))
    await screen.findByText('5.6 mmol/L')
    expect(api.getLabReport).toHaveBeenCalledWith('261009000127')
    expect(screen.getByText('3.5 to 5.1 mmol/L')).toBeTruthy()
  })

  it('prints the server print copy and nothing else', async () => {
    api.getLabReport.mockResolvedValue(REPORT)
    api.printLabReport.mockResolvedValue({ ...REPORT, printed_at: '2026-10-09T08:00:00+00:00',
      printed_by: { name: 'Anil Kumar' } })
    render(<ReportsView {...props} />)
    fireEvent.change(screen.getByLabelText('Accession number'), { target: { value: '261009 00012 7' } })
    fireEvent.click(screen.getByRole('button', { name: 'Open report' }))
    await screen.findByText('5.6 mmol/L')
    fireEvent.click(screen.getByRole('button', { name: 'Print report' }))
    await waitFor(() => expect(api.printLabReport).toHaveBeenCalledWith('261009000127'))
    await waitFor(() => {
      const portal = document.body.querySelector(':scope > .lab-report-print-layout')
      expect(portal).toBeTruthy()
      expect(portal?.textContent).toContain('Printed')
    })
    await waitFor(() => expect(print).toHaveBeenCalledTimes(1))
  })

  it('says a misread accession in words', async () => {
    api.getLabReport.mockRejectedValue(new LabApiError('bad check digit', 422, 'bad_accession'))
    render(<ReportsView {...props} />)
    fireEvent.change(screen.getByLabelText('Accession number'), { target: { value: '261009000128' } })
    fireEvent.click(screen.getByRole('button', { name: 'Open report' }))
    expect((await screen.findByRole('alert')).textContent)
      .toBe('That number is not a valid accession. Check the digits and scan again.')
  })

  it('finds a patient by UHID', async () => {
    render(<ReportsView {...props} />)
    await screen.findByRole('table')
    api.listLabReports.mockResolvedValue(list({ uhid: 'MRN-0042', day: null }))
    fireEvent.change(screen.getByLabelText('UHID'), { target: { value: ' MRN-0042 ' } })
    fireEvent.click(screen.getByRole('button', { name: 'Find reports' }))
    await screen.findByText('Reports for UHID MRN-0042')
    expect(api.listLabReports).toHaveBeenLastCalledWith({ uhid: 'MRN-0042' })
  })

  it('never shows a failed load as an empty list', async () => {
    api.listLabReports.mockRejectedValue(new LabApiError('The audit trail is not available', 503,
      'audit_unavailable'))
    render(<ReportsView {...props} />)
    expect((await screen.findByRole('alert')).textContent).toContain('The audit trail is not available')
    expect(screen.queryByText('No reports here.')).toBeNull()
  })

  it('hands a switched-off module to the panel', async () => {
    api.listLabReports.mockRejectedValue(new LabApiError('off', 404, 'module_disabled'))
    const onModuleOff = vi.fn()
    render(<ReportsView {...props} onModuleOff={onModuleOff} />)
    await waitFor(() => expect(onModuleOff).toHaveBeenCalled())
  })
})
